"""Dynamic eval generation: the model authors trigger prompts and execution
cases (with inline file fixtures) from the skill itself.

Known bias: a model generating tests from a skill tends to generate tests the
skill passes. The prompt pushes against this (outcome checks, adversarial
cases, near-miss triggers), and generated files are marked for human review —
but treat generated evals as coverage, not proof.
"""

from __future__ import annotations

import pathlib
import re

import yaml

from ..manifest import Manifest, load_all
from .checks import _CHECKS
from .runner import ask_json

GEN_HEADER = "# generated by `skill gen-evals` — review before trusting\n"

GEN_PROMPT = """You are generating evaluation scenarios for an AI coding agent "skill" (a reusable \
instruction module the agent loads when its description matches the user's request).

THE SKILL UNDER TEST (full text):
{skill_md}

OTHER SKILLS IN THE CATALOG (use these to craft realistic near-misses):
{catalog}

EXISTING TRIGGER PROMPTS (generate different ones):
{existing_triggers}

EXISTING EXECUTION CASE NAMES (generate different scenarios):
{existing_cases}

Generate:
1. "should_trigger": {n_triggers} new realistic user prompts that SHOULD make an agent load \
this skill. Vary phrasing, formality, and indirection — include at least one prompt that \
implies the situation without using the skill's own keywords.
2. "should_not_trigger": {n_triggers} new NEAR-MISS prompts — same territory, but outside the \
skill's stated scope, so the skill should NOT load. Unrelated prompts are worthless as negatives.
3. "cases": {n_cases} new execution cases. Each case is an object with:
   - "name": short kebab-case identifier
   - "task": the instruction a user would give the agent
   - "files": object mapping relative file paths to full file contents — a small, realistic \
project the agent will work inside. Include everything needed to make the scenario concrete \
(scripts, configs, docs). Shell scripts will be made executable.
   - "checks": list of objects using ONLY this vocabulary:
       {{"transcript_mentions": "<string>"}} — string must appear in the agent's transcript
       {{"command_matching": "<regex>"}} — some Bash command the agent runs must match
       {{"no_command_matching": "<regex>"}} — no Bash command the agent runs may match
       {{"file_exists": "<relative path>"}} — file must exist in the sandbox afterward
       {{"file_absent": "<relative path>"}} — file must not exist afterward
     Prefer checks that observe TASK OUTCOMES in the sandbox over recall of the skill's wording.
   - "judge": a rubric (2-4 sentences) for a pairwise judge comparing a with-skill and a \
without-skill transcript: what makes one transcript better.

At least one case must be ADVERSARIAL: the fixture is constructed so that doing the task \
naively goes wrong, and following the skill's guidance is what avoids the failure. Make \
fixtures hard enough that a competent agent WITHOUT the skill plausibly fails a check.

Respond with ONLY a JSON object:
{{"should_trigger": [...], "should_not_trigger": [...], "cases": [{{...}}, ...]}}
"""


def generate(repo_root: pathlib.Path, skill: Manifest, n_cases: int = 3,
             n_triggers: int = 4) -> dict:
    """Generate evals and write them into the skill's evals/ directory.

    Returns a summary dict: what was added and what was dropped in validation.
    """
    catalog = "\n".join(f"- {m.name}: {m.description}"
                        for m in load_all(repo_root) if m.name != skill.name) or "(none)"
    existing_triggers = _existing_triggers(skill)
    existing_cases = [p.stem for p in skill.execution_cases()]

    raw = ask_json(GEN_PROMPT.format(
        skill_md=skill.path.read_text(encoding="utf-8"),
        catalog=catalog,
        existing_triggers=yaml.safe_dump(existing_triggers, default_flow_style=False) or "(none)",
        existing_cases=", ".join(existing_cases) or "(none)",
        n_cases=n_cases, n_triggers=n_triggers,
    ), timeout=600)

    summary = {"triggers_added": 0, "cases_written": [], "dropped": []}
    _merge_triggers(skill, raw, existing_triggers, summary)
    _write_cases(skill, raw.get("cases") or [], existing_cases, summary)
    return summary


def _existing_triggers(skill: Manifest) -> dict:
    tf = skill.triggers_file()
    if tf is None:
        return {"should_trigger": [], "should_not_trigger": []}
    data = yaml.safe_load(tf.read_text(encoding="utf-8")) or {}
    return {"should_trigger": list(data.get("should_trigger") or []),
            "should_not_trigger": list(data.get("should_not_trigger") or [])}


def _merge_triggers(skill: Manifest, raw: dict, existing: dict, summary: dict) -> None:
    merged = {k: list(v) for k, v in existing.items()}
    for key in ("should_trigger", "should_not_trigger"):
        for prompt in raw.get(key) or []:
            prompt = str(prompt).strip()
            if prompt and prompt not in merged["should_trigger"] \
                    and prompt not in merged["should_not_trigger"]:
                merged[key].append(prompt)
                summary["triggers_added"] += 1
    if summary["triggers_added"]:
        skill.evals_dir.mkdir(exist_ok=True)
        (skill.evals_dir / "triggers.yaml").write_text(
            GEN_HEADER + yaml.safe_dump(merged, default_flow_style=False,
                                        allow_unicode=True, sort_keys=False),
            encoding="utf-8")


def _write_cases(skill: Manifest, cases: list, existing: list[str], summary: dict) -> None:
    cases_dir = skill.evals_dir / "cases"
    cases_dir.mkdir(parents=True, exist_ok=True)
    for case in cases:
        name = re.sub(r"[^a-z0-9-]", "-", str(case.get("name", "")).lower()).strip("-")
        if not name or not case.get("task"):
            summary["dropped"].append(f"{case.get('name')!r}: missing name or task")
            continue
        if name in existing or (cases_dir / f"gen-{name}.yaml").exists():
            summary["dropped"].append(f"{name}: duplicate of an existing case")
            continue
        checks, bad = [], []
        for c in case.get("checks") or []:
            if isinstance(c, dict) and len(c) == 1 and next(iter(c)) in _CHECKS:
                checks.append({k: str(v) for k, v in c.items()})
            else:
                bad.append(str(c))
        if bad:
            summary["dropped"].append(f"{name}: dropped invalid checks {bad}")
        files = {str(p): str(content) for p, content in (case.get("files") or {}).items()
                 if not str(p).startswith(("/", ".."))}
        doc = {"task": str(case["task"]), "files": files, "checks": checks,
               "judge": str(case.get("judge", "")).strip()}
        path = cases_dir / f"gen-{name}.yaml"
        path.write_text(
            GEN_HEADER + yaml.safe_dump(doc, default_flow_style=False,
                                        allow_unicode=True, sort_keys=False),
            encoding="utf-8")
        summary["cases_written"].append(str(path.relative_to(skill.skill_dir.parent.parent)))
